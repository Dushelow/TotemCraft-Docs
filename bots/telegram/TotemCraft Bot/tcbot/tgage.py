"""Примерная дата регистрации аккаунта Telegram по его ID.

Telegram не сообщает ботам дату регистрации. ID выдаются примерно по возрастанию,
поэтому месяц регистрации оценивается по опорным точкам «ID -> месяц»:
- до 2025 года — открытый набор github.com/jobians/telegram-id-age (MIT), сглаженный так,
  чтобы дата не убывала с ростом ID, по одной точке на квартал;
- 2026 год — самые свежие ID, подававшие заявки в нашего бота в каждом месяце
  (аккаунт с таким ID точно уже существовал в этом месяце);
- плюс та же граница, которую бот считает на лету по своей истории заявок.
Точность: для аккаунтов после 2022 года обычно ±2-3 месяца, для старых — до года.
"""
from datetime import date, timedelta

# (ID, 'ГГГГ-ММ'): аккаунт с этим ID зарегистрирован примерно в этом месяце
ANCHORS = [
    (0, '2013-08'), (2768409, '2013-11'), (11538514, '2014-02'), (44634663, '2014-05'),
    (54845238, '2014-09'), (63263518, '2014-10'), (101260938, '2015-03'), (103151531, '2015-05'),
    (112594714, '2015-07'), (133909606, '2015-10'), (171295414, '2016-03'), (181783990, '2016-04'),
    (278941742, '2016-09'), (285253072, '2016-10'), (328594461, '2017-01'), (400169472, '2017-07'),
    (805158066, '2019-07'), (1974255900, '2021-10'), (5045293264, '2022-01'), (5308260177, '2022-04'),
    (5442755368, '2022-07'), (5601951167, '2022-10'), (5802659303, '2023-01'), (5994561143, '2023-04'),
    (6326011828, '2023-07'), (6401027363, '2023-11'), (6559717847, '2024-01'), (7002435197, '2024-04'),
    (7243375923, '2024-07'), (7450316621, '2024-10'), (7591351660, '2025-01'), (7834356221, '2025-06'),
    (8179125032, '2025-07'), (8384648263, '2025-10'),
    # граница по заявкам бота TotemCraft
    (8772155835, '2026-04'), (8903185588, '2026-05'), (8929707268, '2026-06'), (8986150119, '2026-07'),
]
# Сколько новых ID Telegram выдаёт в месяц (по 2025-2026 годам) — для ID новее последней точки
IDS_PER_MONTH = 45_000_000


def _month_start(ym):
    y, m = map(int, ym.split('-'))
    return date(y, m, 1)


def _points(extra=()):
    """Опорные точки, упорядоченные по ID, с неубывающей датой."""
    pts = sorted([(i, _month_start(ym)) for i, ym in ANCHORS] + list(extra))
    out = []
    for i, d in pts:
        if out and d < out[-1][1]:
            d = out[-1][1]
        out.append((i, d))
    return out


def estimate(tg_id, extra=(), today=None):
    """Примерная дата регистрации (date, первое число месяца) по ID."""
    today = today or date.today()
    pts = _points(extra)
    tg_id = int(tg_id)
    if tg_id >= pts[-1][0]:
        months = (tg_id - pts[-1][0]) / IDS_PER_MONTH
        est = pts[-1][1] + timedelta(days=30.4 * months)
        return min(est, today).replace(day=1)
    for (i1, d1), (i2, d2) in zip(pts, pts[1:]):
        if i1 <= tg_id < i2:
            frac = (tg_id - i1) / (i2 - i1) if i2 > i1 else 0
            return (d1 + timedelta(days=(d2 - d1).days * frac)).replace(day=1)
    return pts[0][1]


MONTHS = ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль', 'август',
          'сентябрь', 'октябрь', 'ноябрь', 'декабрь']


def age_text(created, today=None):
    """«около 2 лет», «около 5 месяцев», «меньше месяца»."""
    today = today or date.today()
    months = (today.year - created.year) * 12 + today.month - created.month
    if months < 1:
        return "меньше месяца"
    if months < 12:
        return f"около {months} мес."
    years = months / 12
    if years < 1.5:
        return "около года"
    if years < 2:
        return "около полутора лет"
    n = int(round(years))
    word = "года" if n % 10 == 1 and n % 100 != 11 else "лет"  # «около 21 года», «около 3 лет»
    return f"около {n} {word}"


def describe(tg_id, extra=(), today=None):
    """Строка для карточки: «≈ март 2024 (около 2 лет)»."""
    created = estimate(tg_id, extra, today)
    return f"≈ {MONTHS[created.month - 1]} {created.year} ({age_text(created, today)})"
